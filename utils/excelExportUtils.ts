const HEADER_STYLE: Partial<ExcelJS.Style> = {
    font: { bold: true, color: { argb: 'FFFFFFFF' }, size: 12 },
    fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4B2A63' } },
    alignment: { horizontal: 'center', vertical: 'middle' }
};

const BRANDING_STYLE: Partial<ExcelJS.Style> = {
    font: { bold: true, color: { argb: 'FF4B2A63' }, size: 16, italic: true },
    alignment: { horizontal: 'left', vertical: 'middle' }
};

const addBranding = (sheet: ExcelJS.Worksheet, businessName: string, section: string) => {
    sheet.mergeCells('A1:G1');
    const cell = sheet.getCell('A1');
    cell.value = `OB Pro Terminal | ${businessName} | ${section} | Generated by OB`;
    cell.style = BRANDING_STYLE;
    sheet.getRow(1).height = 35;
    sheet.getRow(2).values = [] as any; // Spacer
};

const addDataSheet = (workbook: ExcelJS.Workbook, name: string, columns: Partial<ExcelJS.Column>[], data: any[], businessName: string, section: string) => {
    const sheet = workbook.addWorksheet(name);
    addBranding(sheet, businessName, section);
    
    // Set columns starting from row 3
    sheet.getRow(3).values = columns.map(c => c.header) as any;
    sheet.columns = columns.map(c => ({ ...c, header: undefined })); 
    
    columns.forEach((col, idx) => {
        const cell = sheet.getCell(3, idx + 1);
        cell.value = col.header as any;
        cell.style = HEADER_STYLE;
        sheet.getColumn(idx + 1).width = col.width || 15;
        sheet.getColumn(idx + 1).key = col.key;
    });

    data.forEach((item) => {
        sheet.addRow(item);
    });

    return sheet;
};

